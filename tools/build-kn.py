"""Build the Kannada (Prajavani) page, the site default, from the English index.en.html and content/i18n/kn.json.

    index.html                          the Kannada page (default; index.en.html is the English source)
    index.pv.cms.html                   the same page for the Prajavani CMS, loading its files from Cloudflare Pages
    content/i18n/kn-translation.csv     the same text as a spreadsheet, for editors to review

kn.json has three parts:
    "page"     exact snippets of index.en.html (en) and their Kannada replacement (kn)
    "strings"  text shown by site/main.js and site/greeting.js, keyed as in t('key', 'English')
    "site"     edition settings (language, publisher, sponsor, stories file)
"site" and "strings" are written into the page as window.DASARA_SITE / window.DASARA_STRINGS, which
main.js and greeting.js read (the names are kept from the Dasara page this site was built from).

Run after changing index.en.html, the scripts' English text, or kn.json:

    python tools/build-kn.py

The build stops if a "page" snippet is no longer in index.en.html (someone edited the English), or if a
script string has no Kannada. It lists any English text still visible on the Kannada page.
"""
import csv
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
ASSET_HOST = 'https://deepawali.pages.dev/'  # Cloudflare Pages copy of this repo
html = (root / 'index.en.html').read_text(encoding='utf-8')
edition = json.loads((root / 'content/i18n/kn.json').read_text(encoding='utf-8'))
site = edition['site']
problems = []


def replace(page, old, new, what):
    if old not in page:
        problems.append(f'{what}: text not found in index.en.html (was the English edited?):\n    {old[:140]}')
        return page
    return page.replace(old, new)


page = html
for item in edition['page']:
    page = replace(page, item['en'], item['kn'], f'kn.json page item {item["id"]}')

# Every string the scripts can show must have Kannada, and its English must still match the script.
script_english = {}
for name in ('site/main.js', 'site/greeting.js'):
    # English in single quotes, or in double quotes when it has an apostrophe.
    for match in re.finditer(r"""\bt\('([\w.]+)',\s*(?:'([^']*)'|"([^"]*)")""", (root / name).read_text(encoding='utf-8')):
        script_english.setdefault(match.group(1), match.group(2) if match.group(2) is not None else match.group(3))
script_english.pop('key', None)  # the example in main.js's comment
for key, english in script_english.items():
    entry = edition['strings'].get(key)
    if not entry or not entry.get('kn'):
        problems.append(f'kn.json strings: no Kannada for "{key}" ({english})')
    elif entry.get('en') != english:
        problems.append(f'kn.json strings: English of "{key}" changed in the script; check the Kannada.\n'
                        f'    kn.json: {entry.get("en")}\n    script:  {english}')

page = replace(page, '<html lang="en">', f'<html lang="{site["lang"]}">', 'html tag')
# Kannada text uses Prajavani's own text font (declared in site/style.css); warm up its CDN.
page = replace(page, '  <link rel="preconnect" href="https://fonts.googleapis.com">',
               '  <link rel="preconnect" href="https://fea.assettype.com" crossorigin>\n  <link rel="preconnect" href="https://fonts.googleapis.com">',
               'preconnect')
strings = {key: value['kn'] for key, value in edition['strings'].items()}
settings = ('  <!-- Edition settings, generated by tools/build-kn.py from content/i18n/kn.json. Edit that file and rebuild;\n'
            '       do not edit this page by hand. -->\n'
            f'  <script>window.DASARA_SITE = {json.dumps(site, ensure_ascii=False)};\n'
            f'  window.DASARA_STRINGS = {json.dumps(strings, ensure_ascii=False)};</script>\n')
page = replace(page, '  <script src="site/main.js" defer></script>', settings + '  <script src="site/main.js" defer></script>', 'scripts')

if problems:
    sys.exit('Kannada page not built:\n  ' + '\n  '.join(problems))

# English text left on the page (outside scripts, styles and SVG). Brand and network names are fine.
visible = re.sub(r'<(script|style|svg)\b.*?</\1>', '', page, flags=re.S)
allowed = {'WhatsApp', 'Facebook', 'X', 'English'}
leftovers = sorted({text.strip() for text in re.findall(r'>([^<>]*[A-Za-z]{3,}[^<>]*)<', visible)
                    if not re.search('[ಀ-೿]', text) and text.strip() not in allowed})
leftovers += sorted({value for value in re.findall(r'(?:aria-label|alt|placeholder|content)="([^"]*[A-Za-z]{4,}[^"]*)"', visible)
                     if not re.search('[ಀ-೿]', value) and not value.startswith(('width=', '#', 'http'))
                     and value not in ('website', 'summary_large_image', 'index, follow, max-image-preview:large')})
if leftovers:
    print('  English text still on the Kannada page (add it to kn.json):\n    ' + '\n    '.join(leftovers))

(root / 'index.html').write_text(page, encoding='utf-8')
print('index.html (Kannada, the default page) written')

# The page pasted into the Prajavani CMS (www.prajavani.net/pages/deepawali): the same page, with the
# scripts, styles and artwork loaded from the Cloudflare Pages copy of this repo (served with CORS; see _headers).
cms = page.replace('="site/', f'="{ASSET_HOST}site/').replace('href="index.en.html"', f'href="{ASSET_HOST}index.en.html"')
left = re.findall(r'(?:src|href)="(?!https?:|#|mailto:)([^"]+)"', cms)
if left:
    sys.exit('index.pv.cms.html: relative links left: ' + ', '.join(sorted(set(left))))
(root / 'index.pv.cms.html').write_text(cms, encoding='utf-8')
print(f'index.pv.cms.html (for the Prajavani CMS, assets from {ASSET_HOST}) written')

# Review sheet for editors (the build reads kn.json, not this file).
with (root / 'content/i18n/kn-translation.csv').open('w', encoding='utf-8-sig', newline='') as sheet:
    writer = csv.writer(sheet)
    writer.writerow(['Section', 'Key', 'English', 'Kannada', 'Notes'])
    strip = lambda text: re.sub(r'\s+', ' ', re.sub(r'<[^>]+>|^[^>]*>|<[^<]*$|\b[\w-]+="', ' ', text)).strip(' ">')
    for item in edition['page']:
        writer.writerow(['page', item['id'], strip(item['en']), strip(item['kn']), ''])
    for key, value in edition['strings'].items():
        writer.writerow(['strings', key, value['en'], value['kn'], ''])
print('content/i18n/kn-translation.csv written (for review; edit kn.json to change the page)')
